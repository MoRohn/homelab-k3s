"""Ask and the command bar: /api/ai/* (threads, streaming messages, capabilities) and /api/command.

Spec §7–§11, §18–§21, §64, §67–§70.

Streaming. POST /api/ai/threads/{id}/messages answers with text/event-stream: `route` (as soon as the
gateway picks a model; an early one with just the mode so the screen isn't blank while a request
queues), `delta` (text), then `receipt` or `error`, then `done`. The gateway call runs in its own task
that does not depend on the browser: if the phone locks or the tab closes, the answer keeps arriving,
is saved, and is pushed to every other device of the owner as hub `thread` events (~1 s cadence), so
"Open on desktop" shows the same answer (§68). The final message is persisted before `done` is sent.

Gateway contract (lif/gateway/app.py): X-LIF-* headers arrive with the stream; the chunk carrying
`usage` also carries `lif` (alias, served_by, model, fallback, degraded, reason, route_decision). An
upstream 4xx comes back as HTTP 200 whose lines are raw JSON errors; a mid-stream failure is a
`data: {"error": …}` line with no [DONE]. A 429 of type capacity means the request waited 120 s for a
slot while BLERBZ had the GPU.

This module talks to the gateway with its own small httpx client (`_client`) because the shared
upstream.stream() helper yields lines only: Ask needs the response's X-LIF-* headers for the route, and the
error body's `type` (capacity vs rate_limit) to explain a 429. It calls exactly one path. The key never leaves
this process: not in errors, not in tech details, not in logs.

Privacy (brief §3): "Local only" sends X-LIF-Data-Class CONFIDENTIAL, so local/auto routes with built-in
rules; "Allow Jev routing" sends PUBLIC, which lets local/auto show the prompt to Jev to choose a
model. The answer is always generated by a local model.

Owner: AI.
"""
