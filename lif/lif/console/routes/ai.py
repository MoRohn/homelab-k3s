@router.post("/command", response_model=CommandResolution)
async def command(req: CommandRequest, user: User = Depends(auth.require("read"))) -> CommandResolution:
    """Deterministic resolution; never executes anything (operational commands come back as a ProposedAction)."""
    text = req.text.strip()
    if not text:
        raise human(422, "Type a command or a question", "Nothing was run.", "Try “Why is the GPU busy?”.")
    if len(text) > 4000:
        raise human(422, "That's too long for the command bar", "Nothing was run.", "Use Ask for long prompts.",
                    [("Open Ask", "/ask")])
    out = intent.resolve(text, poller.snapshot(), user)
    if out.kind == "knowledge_query":
        await _knowledge_preview(out, text)
    log.event(LOG, "command", kind=out.kind, confidence=out.confidence, chars=len(text))
    return out


async def _knowledge_preview(out: CommandResolution, text: str) -> None:
    """Show the best few knowledge matches inline; the full search stays one tap away (navigate)."""
    from lif.console.routes import knowledge   # sibling route module; imported late to keep startup light

    try:
        hits = await knowledge.search_hits(text, limit=3)
    except Exception as e:              # knowledge down or not bundled: the navigate link still works
        log.event(LOG, "command_knowledge_failed", error=type(e).__name__)
        return
    if not hits:
        out.answer = "No matching decisions, evidence or assumptions were found. Open Knowledge to search differently."
        return
    best = hits[0]
    out.answer = f"**{best.title}**" + (f" — {best.summary}" if best.summary else "")
    out.facts = [Fact(label=h.type.capitalize() or "Item", value=h.title) for h in hits]
    out.navigate = f"/knowledge/o/{quote(best.key, safe='')}" if len(hits) == 1 else out.navigate
