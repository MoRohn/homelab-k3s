# Mode → (gateway alias, label, contextual help §96), from the one role table in humanize. Users pick
# capabilities, never physical models (§10).
MODES: dict[AskMode, tuple[str, str, str]] = {
    m: humanize.ROLE_BY_KEY[m][1:4] for m in ("auto", "fast", "balanced", "deep", "code", "vision")}  # type: ignore[misc]
DATA_CLASS: dict[PrivacyChoice, str] = {"local_only": "CONFIDENTIAL", "allow_jev": "PUBLIC"}

TEXT_KINDS = {"text", "code", "log", "markdown", "json", "csv", "document", "other"}
MAX_PROMPT_CHARS = 512 * 1024          # the gateway refuses bodies over 4 MiB; JSON escaping can double text
MAX_FILE_CHARS = 256 * 1024            # brief §1: ≤ 256 KB per file, extracted in the browser
MAX_FILES = 10
MAX_ATTACH_CHARS = 1024 * 1024
FLUSH_SEC = 1.0                        # partial-answer cadence for the DB and other devices
REQUEST_TIMEOUT = httpx.Timeout(300.0, connect=3.0)   # the gateway may queue up to 120 s, then stream

# Tests replace this with httpx.MockTransport; production uses the default network transport.
_transport: httpx.AsyncBaseTransport | None = None


def _client() -> httpx.AsyncClient:
    return httpx.AsyncClient(base_url=settings.gateway_url(), transport=_transport, timeout=REQUEST_TIMEOUT)


def _alias_label(alias: str) -> str:
    for r in poller.snapshot().roles:
        if r.alias == alias and r.label:
            return r.label
    return humanize.role_label(alias)


def friendly_model(profile: str | None) -> str | None:
    """Profile id → the name people see: the catalogue name if the poller knows it, else humanize's
    tidy version of the id ('qwen3-4b-instruct-2507-q4km-cpu' → 'Qwen3 4B Instruct 2507 (CPU)')."""
    if not profile:
        return None
    snap = poller.snapshot()
    for d in snap.deployments:
        if d.id == profile and d.name:
            return d.name
    for r in snap.roles:
        if r.served_by == profile and r.model_name:
            return r.model_name
    return humanize.model_name(profile) or profile


def model_device(profile: str | None) -> str | None:
    """Where a profile runs ('CPU' / 'GPU') as the registry or routing table records it; None when unknown —
    the receipt never guesses (§9 'Handled by … · GPU')."""
    if not profile:
        return None
    snap = poller.snapshot()
    dev = next((d.device for d in snap.deployments if d.id == profile and d.device), None)
    if dev is None:
        for src in (snap.raw.get("routing"), snap.raw.get("capabilities")):
            profs = src.get("profiles") if isinstance(src, dict) else None
            p = profs.get(profile) if isinstance(profs, dict) else None
            if isinstance(p, dict) and p.get("device"):
                dev = str(p["device"])
                break
    return dev.upper() if dev else None


def reason_label(reason: str | None, *, fallback: bool = False, degraded: bool = False) -> str | None:
    """Gateway reason (free text, router.py) → one human sentence (shared rules in humanize); raw stays in tech."""
    return humanize.role_cause(reason, fallback=fallback, degraded=degraded)[1] if reason else None


